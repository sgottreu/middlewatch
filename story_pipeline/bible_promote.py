def _git(*args, check=True):
    r = subprocess.run(["git", *args], capture_output=True, text=True, timeout=60)
    if check and r.returncode != 0:
        raise PromoteError((r.stderr or r.stdout).strip() or f"git {args[0]} failed")
    return r


def commit(files: list[Path], name: str, message: str, push: bool) -> dict:
    """Commit exactly these files and push without force. Mirrors casting apply:
    a failed push leaves the commit on disk and says so."""
    try:
        _git("rev-parse", "--is-inside-work-tree")
    except Exception as e:
        return {"committed": False, "message": f"not a git checkout: {e}"}
    paths = sorted({str(f) for f in files if Path(f).exists()})
    for _ in range(5):
        if not Path(".git/index.lock").exists():
            break
        time.sleep(1)
    _git("add", "--", *paths)
    if _git("diff", "--cached", "--quiet", "--", *paths, check=False).returncode == 0:
        return {"committed": False, "message": "nothing to commit — already up to date"}
    who = []
    if not _git("config", "user.name", check=False).stdout.strip():
        who = ["-c", "user.name=Middle Watch review", "-c", "user.email=sgottreu@gmail.com"]
    r = subprocess.run(["git", *who, "commit", "-q", "-m",
                        f"bible: promote {name}\n\n{message}", "--", *paths],
                       capture_output=True, text=True, timeout=60)
    if r.returncode != 0:
        raise PromoteError((r.stderr or r.stdout).strip() or "git commit failed")
    out = {"committed": True, "sha": _git("rev-parse", "--short", "HEAD").stdout.strip(),
           "files": paths, "pushed": False}
    if push:
        pr = _git("push", "-q", check=False)
        if pr.returncode == 0:
            out["pushed"] = True
        else:
            out["push_error"] = (pr.stderr or pr.stdout).strip()
    return out


def git_state(paths: list[Path]) -> dict:
    """Where a commit and push from here would go, and what else would ride
    along. `ahead` counts commits already waiting to be pushed: a push sends
    them too, so the confirm step says so rather than surprising anyone."""
    out = {"repo": False, "branch": None, "upstream": None, "ahead": None,
           "dirty": [], "waiting": [], "uncommitted": []}
    try:
        if _git("rev-parse", "--is-inside-work-tree", check=False).returncode != 0:
            return out
    except Exception:
        return out
    out["repo"] = True
    out["branch"] = _git("rev-parse", "--abbrev-ref", "HEAD", check=False).stdout.strip() or None
    up = _git("rev-parse", "--abbrev-ref", "--symbolic-full-name", "@{u}", check=False)
    if up.returncode == 0 and up.stdout.strip():
        out["upstream"] = up.stdout.strip()
        n = _git("rev-list", "--count", "@{u}..HEAD", check=False).stdout.strip()
        out["ahead"] = int(n) if n.isdigit() else None
        log = _git("log", "--format=%h%x09%s", "@{u}..HEAD", check=False).stdout
        out["waiting"] = [dict(zip(("sha", "subject"), ln.split("\t", 1)))
                          for ln in log.splitlines() if "\t" in ln]
    st = _git("status", "--porcelain", "--", *[str(x) for x in paths], check=False)
    out["dirty"] = [ln[3:] for ln in st.stdout.splitlines() if ln.strip()]
    # Tracked files changed but not committed, other than the ones Apply
    # commits. Reported, never committed from here.
    mine = {str(x) for x in paths}
    st = _git("status", "--porcelain", "--untracked-files=no", check=False)
    out["uncommitted"] = [ln[3:] for ln in st.stdout.splitlines()
                          if ln.strip() and ln[3:] not in mine]
    return out


def push_waiting(paths: list[Path] | None = None) -> dict:
    """Push the commits already on this branch and nothing else: no new commit,
    never forced. A refusal comes back with git's own message."""
    before = git_state(paths or [])
    if not before["repo"]:
        raise PromoteError("not a git checkout")
    if not before["upstream"]:
        raise PromoteError(f"{before['branch']} has no upstream to push to")
    if not before["ahead"]:
        return {"pushed": False, "count": 0, "message": "nothing waiting to push",
                "git": before}
    r = _git("push", "-q", check=False)
    after = git_state(paths or [])
    out = {"pushed": r.returncode == 0, "count": before["ahead"],
           "upstream": before["upstream"], "git": after}
    if r.returncode != 0:
        out["push_error"] = (r.stderr or r.stdout).strip()
    return out


def apply_plan(name: str, cfg: dict | None = None,
               bibles_dir: str | Path | None = None) -> dict:
    """What Apply would write and commit. Free; writes nothing."""
    cfg = cfg or {}
    root = bibles_dir or cfg.get("bibles_dir", "bibles")
    pv = preview(name, cfg, root)
    log = changelog.path_for(pv.bible)
    diff = pv.diff().splitlines()
    files = [
        {"path": str(pv.bible),
         "action": ("unchanged" if not pv.changed
                    else "update" if pv.current else "create"),
         "added": sum(1 for l in diff if l.startswith("+") and not l.startswith("+++")),
         "removed": sum(1 for l in diff if l.startswith("-") and not l.startswith("---"))},
        {"path": str(log),
         "action": ("unchanged" if not pv.changed
                    else "append" if log.exists() else "create")},
        {"path": str(pv.draft), "action": "commit"},
    ]
    return {"name": name, "blocked": pv.blocked, "changed": pv.changed,
            "errors": [p for p in pv.problems if p["fatal"]],
            "summary": summary(pv), "files": files,
            "git": git_state([pv.draft, pv.bible, log])}


def apply(name: str, cfg: dict | None = None, author: str | None = None,
          do_commit: bool = True, push: bool = True,
          bibles_dir: str | Path | None = None) -> dict:
    cfg = cfg or {}
    root = bibles_dir or cfg.get("bibles_dir", "bibles")
    result = promote(name, cfg, author=author, bibles_dir=root)
    if do_commit:
        bpath = bible_path(name, root)
        files = [draft_path(name, root), bpath, changelog.path_for(bpath)]
        result["git"] = commit(files, name, result.get("summary") or "re-promote", push)
    return result
