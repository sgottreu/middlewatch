def draft_path(name: str, bibles_dir: str | Path = "bibles") -> Path:
    return Path(bibles_dir) / name / f"{name}.draft.md"


def bible_path(name: str, bibles_dir: str | Path = "bibles") -> Path:
    return bibles.path_for(name, bibles_dir)


def check_name(name: str) -> str:
    if not re.fullmatch(r"[a-z0-9][a-z0-9_-]*", name or ""):
        raise PromoteError(f"{name!r} is not a bible name")
    return name


