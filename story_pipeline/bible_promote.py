# Writing
# --------------------------------------------------------------------------- #

def summary(pv: Preview) -> str:
    canon = len(pv.meta.get("canon") or [])
    cast = len(pv.meta.get("recurring_cast") or [])
    dropped = [d["title"] for d in pv.dropped if d["reason"] == "working-only"]
    out = (f"Promoted from {pv.draft.name}: {canon} canon fact(s), "
           f"{cast} recurring cast.")
    if dropped:
        out += f" Left in the draft: {', '.join(dropped)}."
    if pv.preserved.get("cast_voices"):
        out += f" Kept voices for {', '.join(pv.preserved['cast_voices'])}."
    return out


def promote(name: str, cfg: dict | None = None, author: str | None = None,
            bibles_dir: str | Path | None = None) -> dict:
    """Write `<name>.md` from the draft and log it. Refuses on any fatal problem.
    A draft that produces what is already there writes nothing and logs nothing."""
    cfg = cfg or {}
    pv = preview(name, cfg, bibles_dir)
    if pv.blocked:
        raise PromoteError(
            f"bible check found {sum(p['fatal'] for p in pv.problems)} error(s); "
            "nothing written:\n" + "\n".join(
                f"  {p['where']}: {p['message']}" for p in pv.problems if p["fatal"]))
    if not pv.changed:
        return {"written": False, "bible": str(pv.bible), "message": "already up to date"}
    pv.bible.parent.mkdir(parents=True, exist_ok=True)
    pv.bible.write_text(pv.text)
    log = changelog.append(pv.bible, summary(pv),
                           author=changelog.resolve_author(author, cfg),
                           kind="promote", series=pv.meta.get("series"))
    return {"written": True, "bible": str(pv.bible), "changelog": str(log),
            "summary": summary(pv)}


# --------------------------------------------------------------------------- #
# Filling a missing detail into the draft
# --------------------------------------------------------------------------- #

def _label(key: str, table: dict) -> str:
    return next(k for k, v in table.items() if v == key).capitalize()


def fill_draft(text: str, field_id: str, value) -> str:
    """`text` with one field set. `field_id` is what a preview problem names:
    `genre`, `series`, `anchor_year`, or `cast:<name>:<attr>`."""
    value = re.sub(r"\s+", " ", str(value)).strip()
    if not value:
        raise PromoteError("empty value")
    lines = text.split("\n")

    if field_id in TOP_FIELDS.values():
        label = _label(field_id, TOP_FIELDS)
        first_h2 = next((i for i, ln in enumerate(lines)
                         if re.match(r"^##\s", ln) and not ln.startswith("###")),
                        len(lines))
        for i in range(first_h2):
            m = TOP_LINE.match(lines[i])
            if m and TOP_FIELDS[m["label"].lower()] == field_id:
                lines[i] = f"{label}: {value}"
                return "\n".join(lines)
        h1 = next((i for i in range(first_h2) if lines[i].startswith("# ")), None)
        if h1 is None:
            return "\n".join([f"{label}: {value}", ""] + lines)
        at = h1 + 1
        add = ["", f"{label}: {value}"]
        if at < len(lines) and lines[at].strip():
            add.append("")
        lines[at:at] = add
        return "\n".join(lines)

    m = re.match(r"^cast:(.+):([a-z_]+)$", field_id)
    if not m:
        raise PromoteError(f"unknown field {field_id!r}")
    who, attr = m.group(1), m.group(2)
    draft = parse_draft(text)
    mem = next((c for c in draft.cast if c.name.lower() == who.lower()), None)
    if mem is None:
        raise PromoteError(f"no cast member {who!r} in the draft")
    # Line numbers are into the draft as parsed; frontmatter shifts nothing
    # because parse_draft already added its offset.
    if attr == "name":
        src = lines[mem.line]
        if mem.name not in src:
            raise PromoteError(f"can't find {mem.name!r} on its line")
        lines[mem.line] = src.replace(mem.name, value, 1)
        return "\n".join(lines)
    if attr not in CAST_FIELDS.values():
        raise PromoteError(f"unknown cast field {attr!r}")
    label = _label(attr, CAST_FIELDS)
    qual = f" ({mem.name})" if mem.shared else ""

    if mem.kind == "bullet":
        indent = "  "
        new = f"{indent}- {label}{qual}: {value}"
        j = mem.line + 1
        while j < len(lines) and lines[j].startswith((" ", "\t")) and lines[j].strip():
            hit = CAST_LINE.match(lines[j])
            if hit and CAST_FIELDS[hit["label"].lower()] == attr:
                lines[j] = new
                return "\n".join(lines)
            j += 1
        lines.insert(j, new)
        return "\n".join(lines)

    new = f"- {label}{qual}: {value}"
    end = mem.line + 1
    while end < len(lines) and not re.match(r"^#{2,3}\s", lines[end]):
        end += 1
    for j in range(mem.line + 1, end):
        hit = CAST_LINE.match(lines[j])
        if hit and CAST_FIELDS[hit["label"].lower()] == attr and \
                (hit["who"] or "").strip().lower() in ("", mem.name.lower()) and \
                bool(hit["who"]) == mem.shared:
            lines[j] = new
            return "\n".join(lines)
    k = mem.line + 1
    while k < end and not lines[k].strip():
        k += 1
    if k < end and CAST_LINE.match(lines[k]):
        while k < end and CAST_LINE.match(lines[k]):
            k += 1
        lines.insert(k, new)
    else:
        add = ["", new]
        if mem.line + 1 < len(lines) and lines[mem.line + 1].strip():
            add.append("")
        lines[mem.line + 1:mem.line + 1] = add
    return "\n".join(lines)


def fill(name: str, field_id: str, value, bibles_dir: str | Path = "bibles") -> Path:
    """Write one field into the draft on disk."""
    path = draft_path(check_name(name), bibles_dir)
    if not path.exists():
        raise PromoteError(f"no draft at {path}")
    path.write_text(fill_draft(path.read_text(), field_id, value))
    return path


