@dataclass
class Member:
    name: str
    fields: dict = field(default_factory=dict)
    note: str = ""
    inferred: list = field(default_factory=list)
    line: int = 0          # source line of its heading or bullet
    kind: str = "heading"  # heading | bullet
    shared: bool = False   # one heading holding more than one character


@dataclass
class Draft:
    text: str
    front: dict
    top: dict              # series-level fields from labelled lines
    title: str
    working_title: str
    sections: list         # [(title, body, start_line)]
    cast: list
    cast_intro: str


def _sections(lines: list[str]) -> tuple[list[str], list]:
    """(preamble lines, [(title, body lines, heading line index)])."""
    pre: list[str] = []
    out: list = []
    fence = False
    for i, line in enumerate(lines):
        if line.lstrip().startswith("```"):
            fence = not fence
        m = None if fence else re.match(r"^##\s+(.+?)\s*#*\s*$", line)
        if m and not line.startswith("###"):
            out.append((m.group(1), [], i))
        elif out:
            out[-1][1].append(line)
        else:
            pre.append(line)
    return pre, out


def _paragraphs(lines: list[str]) -> str:
    """Prose lines as one line each per paragraph, joined by a space — a `note`
    is one YAML string."""
    paras, cur = [], []
    for ln in lines:
        if ln.strip():
            cur.append(ln.strip())
        elif cur:
            paras.append(" ".join(cur))
            cur = []
    if cur:
        paras.append(" ".join(cur))
    return " ".join(paras).strip()


def _bullets(lines: list[str]) -> list[str]:
    """Top-level `- ` bullets, continuation lines folded in."""
    out: list[str] = []
    for ln in lines:
        if re.match(r"^[-*]\s+", ln):
            out.append(re.sub(r"^[-*]\s+", "", ln).strip())
        elif ln.strip() and out and (ln.startswith(" ") or ln.startswith("\t")):
            out[-1] += " " + ln.strip()
        elif not ln.strip():
            continue
    return [b for b in out if b]


def _field_value(key: str, raw: str):
    raw = raw.strip().strip("*").strip()
    if key == "age":
        return int(raw) if re.fullmatch(r"\d{1,3}", raw) else raw
    if key == "aliases":
        return [a.strip() for a in raw.split(",") if a.strip()]
    if key == "gender":
        return raw.lower()
    return raw


def _infer_gender(name: str, text: str, sole: bool) -> str | None:
    """female/male from the words nearest the name, or None."""
    def pick(word: str) -> str:
        return "female" if word.lower() in FEMALE else "male"
    m = _GENDER_WORD.search(name)
    if m:
        return pick(m.group(1))
    first = name.split()[0]
    for probe in (name, first):
        for hit in re.finditer(re.escape(probe), text):
            near = _GENDER_WORD.search(text[hit.end(): hit.end() + 80])
            if near:
                return pick(near.group(1))
    if sole:
        m = _GENDER_WORD.search(text)
        if m:
            return pick(m.group(1))
    return None


def _split_names(heading: str) -> tuple[list[str], str | None]:
    """"Garret Marsh (Glasswood mapper)" -> ([Garret Marsh], "Glasswood mapper");
    "The collectors: Tobias Finch and Tess Ridley" -> ([Tobias Finch, Tess Ridley],
    "collectors")."""
    role = None
    m = re.search(r"\(([^)]*)\)\s*$", heading)
    if m:
        role = m.group(1).strip()
        heading = heading[: m.start()].strip()
    if ":" in heading:
        prefix, heading = heading.split(":", 1)
        role = role or re.sub(r"^the\s+", "", prefix.strip(), flags=re.I)
    names = [n.strip() for n in re.split(r",|\s+and\s+|\s*&\s*", heading) if n.strip()]
    return names, role


def _apply_field_lines(members: list[Member], lines: list[str]) -> list[str]:
    """Set fields from labelled lines; return the lines that were prose."""
    prose = []
    for ln in lines:
        m = CAST_LINE.match(ln)
        if not m or not m["value"]:
            prose.append(ln)
            continue
        key = CAST_FIELDS[m["label"].lower()]
        who = (m["who"] or "").strip().lower()
        for mem in members:
            if not who or mem.name.lower() == who:
                mem.fields[key] = _field_value(key, m["value"])
    return prose


def _parse_cast(body: list[str], start: int) -> tuple[list[Member], str]:
    members: list[Member] = []
    if any(ln.startswith("### ") for ln in body):
        intro: list[str] = []
        blocks: list = []
        for j, ln in enumerate(body):
            if ln.startswith("### "):
                blocks.append((ln[4:].strip(), [], start + 1 + j))
            elif blocks:
                blocks[-1][1].append(ln)
            else:
                intro.append(ln)
        for heading, lines, at in blocks:
            names, role = _split_names(heading)
            group = [Member(name=n, line=at, kind="heading", shared=len(names) > 1)
                     for n in names]
            prose = _apply_field_lines(group, lines)
            text = _paragraphs(prose)
            for mem in group:
                if role and "role" not in mem.fields:
                    mem.fields["role"] = role
                mem.note = text
                if "gender" not in mem.fields:
                    g = _infer_gender(mem.name, text, sole=len(group) == 1)
                    if g:
                        mem.fields["gender"] = g
                        mem.inferred.append("gender")
            members += group
        return members, _paragraphs(intro) and "\n".join(intro).strip()

    # Bullet form: `- **Name**: what they are`, fields as indented sub-bullets.
    intro = []
    cur: Member | None = None
    cur_lines: list[str] = []

    def close():
        if cur is None:
            return
        prose = _apply_field_lines([cur], cur_lines)
        if prose:
            cur.note = (cur.note + " " + _paragraphs(prose)).strip()
        if "gender" not in cur.fields:
            g = _infer_gender(cur.name, cur.note, sole=True)
            if g:
                cur.fields["gender"] = g
                cur.inferred.append("gender")
        members.append(cur)

    for j, ln in enumerate(body):
        m = re.match(r"^[-*]\s+\*\*(.+?)\*\*\s*[:—–-]?\s*(.*)$", ln)
        if m:
            close()
            name = m.group(1).strip().rstrip(":").strip()
            cur = Member(name=name, note=m.group(2).strip(), line=start + 1 + j,
                         kind="bullet")
            cur_lines = []
        elif cur is not None and (ln.startswith((" ", "\t")) and ln.strip()):
            cur_lines.append(ln)
        elif cur is not None and not ln.strip():
            continue
        else:
            if cur is not None:
                close()
                cur = None
            intro.append(ln)
    close()
    return members, "\n".join(intro).strip()


def parse_draft(text: str) -> Draft:
    front: dict = {}
    if text.startswith("---"):
        try:
            _, raw, text_body = text.split("---", 2)
            front = yaml.safe_load(raw) or {}
            offset = text[: len(text) - len(text_body)].count("\n")
        except (ValueError, yaml.YAMLError) as e:
            raise PromoteError(f"the draft's frontmatter does not parse: {e}")
    else:
        text_body, offset = text, 0
    lines = text_body.split("\n")
    pre, secs = _sections(lines)
    secs = [(t, b, at + offset) for t, b, at in secs]

    title, top, working = "", {}, ""
    for ln in pre:
        if ln.startswith("# ") and not title:
            title = ln[2:].strip()
            continue
        m = TOP_LINE.match(ln)
        if m and m["value"]:
            key = TOP_FIELDS[m["label"].lower()]
            val = m["value"].strip()
            top[key] = int(val) if key == "anchor_year" and val.isdigit() else val
        w = re.search(r"Working title:\s*(.+?)(?=\s+\(|\s+Status:|$)", ln)
        if w:
            working = w.group(1).strip()

    cast, intro = [], ""
    for t, body, at in secs:
        if bibles.heading_key(t) in CAST_KEYS:
            cast, intro = _parse_cast(body, at)
            break
    return Draft(text=text, front=front, top=top, title=title,
                 working_title=working, sections=secs, cast=cast,
                 cast_intro=intro or "")


