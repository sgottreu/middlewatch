"""Promote a working draft into the pipeline bible.

A series is built in `bibles/<name>/<name>.draft.md` — plain markdown, the same
`##` sections as a bible, no frontmatter needed, which is what Claude Docs
exports. The pipeline only ever reads `bibles/<name>/<name>.md`. This module is
the one road from the first to the second:

    canon bullets              -> `canon`
    each `###` under Recurring Cast (or each `**Name**` bullet under Cast)
                               -> a `recurring_cast` entry, its prose as `note`
    `- Gender: male` lines under a character
                               -> that field, verbatim
    `Genre: fantasy` / `Series: ...` lines before the first `##`
                               -> the frontmatter
    prose sections             -> the body, in draft order
    Story Ideas                -> the body, where only the ideator sees it
    Open Questions, the Minor Names Register, Changelog
                               -> dropped: working notes, never sent to an agent

What it never touches: a `voice` or `portrait` already in `<name>.md` (casting
apply writes those, and a promote must not undo a casting session), and the
series-level `voices`, `art_style` and `minor_names`, which the draft cannot hold.

`preview` writes nothing. `promote` writes only when the result differs, only
when `bible check` finds nothing fatal, and logs the change. `fill_draft` writes
one missing detail back into the draft, so the draft stays the source of truth
and promoting again never loses it. The CLI (`bible promote`) and the review UI
both call these, so they cannot disagree about what a promote does.
"""

from __future__ import annotations

import difflib
import re
import shutil
import subprocess
import tempfile
import time
from dataclasses import dataclass, field
from pathlib import Path

import yaml

from . import bibles, changelog


class PromoteError(RuntimeError):
    pass


# Sections with a job other than "copy the prose".
CANON_KEYS = ("canon", "established facts")
CAST_KEYS = ("recurring cast", "cast")
REGION_KEYS = ("regions",)

# Labels a draft may put on a line of its own. Under a character they set that
# field; before the first `##` they set the series-level one.
CAST_FIELDS = {"age": "age", "gender": "gender", "station": "station",
               "role": "role", "region": "region", "appearance": "appearance",
               "dress": "dress", "aliases": "aliases"}
TOP_FIELDS = {"genre": "genre", "series": "series", "anchor year": "anchor_year"}

# `- Gender: male`, `**Age:** 45`, `Gender (Tess Ridley): female`. The optional
# bracket names the character when one `###` holds two of them.
_LABEL = r"^\s*(?:[-*]\s+)?(?:\*\*)?(?P<label>{labels})(?:\s*\((?P<who>[^)]+)\))?(?:\*\*)?\s*:\s*(?:\*\*)?\s*(?P<value>.*?)\s*$"
CAST_LINE = re.compile(_LABEL.format(labels="|".join(CAST_FIELDS)), re.I)
TOP_LINE = re.compile(_LABEL.format(labels="|".join(TOP_FIELDS)), re.I)

# For a character whose gender the draft does not state: the first of these
# words near their name. Shown as inferred in the preview; a `- Gender:` line in
# the draft always wins.
FEMALE = {"woman", "girl", "mother", "daughter", "sister", "wife", "widow", "aunt"}
MALE = {"man", "boy", "father", "son", "brother", "husband", "widower", "uncle"}
_GENDER_WORD = re.compile(r"\b(" + "|".join(sorted(FEMALE | MALE)) + r")\b", re.I)

HEADER = ("# Generated by `bible promote` from {draft}. Edit the draft and promote\n"
          "# again; edits made here are overwritten, except `voice` and `portrait`\n"
          "# (casting apply), and `voices`, `art_style` and `minor_names`.\n")


