class _Dumper(yaml.SafeDumper):
    """Lists indented under their key, the way the hand-written bibles are —
    casting apply edits `recurring_cast` line by line and expects it."""

    def increase_indent(self, flow=False, indentless=False):
        return super().increase_indent(flow, False)


def _dump(meta: dict) -> str:
    return yaml.dump(meta, Dumper=_Dumper, sort_keys=False, allow_unicode=True,
                     width=10_000, default_flow_style=False)


CAST_ORDER = ("name", "voice", "aliases", "age", "gender", "station", "role",
              "region", "appearance", "dress", "portrait", "note")


def _load_existing(path: Path) -> tuple[dict, str]:
    if not path.exists():
        return {}, ""
    text = path.read_text()
    try:
        return bibles._parse(path).meta, text
    except Exception:
        return {}, text


@dataclass
class Preview:
    name: str
    draft: Path
    bible: Path
    text: str                  # the bible promote would write
    current: str               # what is there now ("" if nothing)
    meta: dict
    kept: list
    dropped: list
    inferred: dict
    preserved: dict
    problems: list = field(default_factory=list)

    @property
    def changed(self) -> bool:
        return self.text != self.current

    @property
    def blocked(self) -> bool:
        return any(p["fatal"] for p in self.problems)

    def diff(self) -> str:
        return "".join(difflib.unified_diff(
            self.current.splitlines(keepends=True), self.text.splitlines(keepends=True),
            fromfile=f"{self.bible.name} (current)" if self.current else "/dev/null",
            tofile=f"{self.bible.name} (promoted)"))

    def to_dict(self) -> dict:
        return {
            "name": self.name,
            "draft": str(self.draft),
            "bible": str(self.bible),
            "exists": bool(self.current),
            "series": self.meta.get("series"),
            "genre": self.meta.get("genre"),
            "canon": list(self.meta.get("canon") or []),
            "cast": [{k: v for k, v in c.items() if k != "note"}
                     | {"inferred": self.inferred.get(c["name"], [])}
                     for c in self.meta.get("recurring_cast") or []],
            "regions": [r["name"] for r in self.meta.get("regions") or []],
            "kept": self.kept,
            "dropped": self.dropped,
            "preserved": self.preserved,
            "problems": self.problems,
            "blocked": self.blocked,
            "changed": self.changed,
            "diff": self.diff(),
        }


def build(name: str, bibles_dir: str | Path = "bibles") -> Preview:
    """What promoting `name` would write. Reads; never writes."""
    check_name(name)
    dpath = draft_path(name, bibles_dir)
    if not dpath.exists():
        raise PromoteError(f"no draft at {dpath}")
    bpath = bible_path(name, bibles_dir)
    draft = parse_draft(dpath.read_text())
    old_meta, current = _load_existing(bpath)

    kept: list = []
    dropped: list = []
    if draft.working_title or any(ln.strip() for ln in [draft.title]):
        dropped.append({"title": "(title and status lines)", "reason": "draft header"})

    # --- series-level --------------------------------------------------------
    meta: dict = {}
    # The working title alone: "Working title: Mapping the Broken Edges
    # (alternative: ...) Status: ..." gives "Mapping the Broken Edges".
    series = (draft.top.get("series") or draft.front.get("series")
              or draft.working_title or old_meta.get("series")
              or name.replace("-", " ").title())
    meta["series"] = series
    genre = draft.top.get("genre") or draft.front.get("genre") or old_meta.get("genre")
    if genre:
        meta["genre"] = genre
    anchor = draft.top.get("anchor_year") or draft.front.get("anchor_year")
    if anchor is not None:
        meta["anchor_year"] = anchor
    preserved: dict = {}
    for key in ("voices", "art_style"):
        if old_meta.get(key):
            meta[key] = old_meta[key]
            preserved[key] = True
    assets = {}
    for key, exts in (("map", ("jpg", "png")), ("layout", ("png", "jpg"))):
        for ext in exts:
            if (dpath.parent / f"{name}.{key}.{ext}").exists():
                assets[key] = f"{name}.{key}.{ext}"
                break
    if assets:
        meta["assets"] = assets

    # --- sections ------------------------------------------------------------
    canon: list[str] = []
    regions: list[dict] = []
    body: list[str] = [f"# {series}", ""]
    for title, lines, _ in draft.sections:
        key = bibles.heading_key(title)
        if key in bibles.WORKING_ONLY:
            dropped.append({"title": title, "reason": "working-only"})
            continue
        if key in CANON_KEYS:
            canon = [re.sub(r"\s+", " ", b) for b in _bullets(lines)]
            kept.append({"title": title, "as": "canon", "count": len(canon)})
            continue
        if key in CAST_KEYS:
            kept.append({"title": title, "as": "recurring_cast",
                         "count": len(draft.cast)})
            if draft.cast_intro.strip():
                body += ["## Recurring Cast", "", draft.cast_intro.strip(), ""]
            continue
        if key in REGION_KEYS:
            for b in _bullets(lines):
                m = re.match(r"^\*\*(.+?):?\*\*:?\s*(.*)$", b)
                if m:
                    first = re.split(r"(?<=[.;])\s", m.group(2).strip(), 1)[0]
                    regions.append({"name": m.group(1).strip().rstrip(":"),
                                    "summary": first.rstrip(".;").strip()})
        chunk = "\n".join(lines).strip()
        if not chunk:
            dropped.append({"title": title, "reason": "empty"})
            continue
        heading = "Story Ideas" if key in bibles.IDEATOR_ONLY else title
        kept.append({"title": title,
                     "as": "ideator only" if key in bibles.IDEATOR_ONLY else "prose"})
        body += [f"## {heading}", "", chunk, ""]

    if canon:
        meta["canon"] = canon

    # --- cast ----------------------------------------------------------------
    old_cast = {str(c.get("name", "")).lower(): c
                for c in old_meta.get("recurring_cast") or [] if isinstance(c, dict)}
    cast: list[dict] = []
    inferred: dict = {}
    voices_kept = []
    for mem in draft.cast:
        entry = {"name": mem.name, **mem.fields}
        if mem.note:
            entry["note"] = mem.note
        old = old_cast.get(mem.name.lower(), {})
        for key in ("voice", "portrait"):
            if old.get(key):
                entry[key] = old[key]
                if key == "voice":
                    voices_kept.append(mem.name)
        cast.append({k: entry[k] for k in CAST_ORDER if k in entry}
                    | {k: v for k, v in entry.items() if k not in CAST_ORDER})
        if mem.inferred:
            inferred[mem.name] = mem.inferred
    if voices_kept:
        preserved["cast_voices"] = voices_kept
    meta["recurring_cast"] = cast
    if regions:
        meta["regions"] = regions
    if old_meta.get("minor_names"):
        meta["minor_names"] = old_meta["minor_names"]
        preserved["minor_names"] = True

    front = HEADER.format(draft=dpath.name) + "\n" + _dump(meta)
    text = f"---\n{front}---\n\n" + "\n".join(body).rstrip() + "\n"
    return Preview(name=name, draft=dpath, bible=bpath, text=text, current=current,
                   meta=meta, kept=kept, dropped=dropped, inferred=inferred,
                   preserved=preserved)


# --------------------------------------------------------------------------- #
# Validation, with each problem mapped to the field that fixes it
# --------------------------------------------------------------------------- #

def _fields_for(p: bibles.Problem, meta: dict) -> list[dict]:
    from . import genres
    where, msg = p.where, p.message
    if where == "genre":
        return [{"id": "genre", "label": "Genre", "type": "select",
                 "options": genres.available(), "value": meta.get("genre")}]
    if where == "series":
        return [{"id": "series", "label": "Series", "type": "text"}]
    if where == "anchor_year":
        return [{"id": "anchor_year", "label": "Anchor year", "type": "number"}]
    m = re.match(r"^cast '(.+)'$|^cast \"(.+)\"$", where)
    if m:
        who = m.group(1) or m.group(2)
        for attr, kind in (("gender", "select"), ("age", "number"),
                           ("appearance", "text"), ("dress", "text"),
                           ("aliases", "text"), ("station", "text"),
                           ("role", "text"), ("region", "text")):
            if re.search(rf"\b`?{attr}`?\b", msg):
                f = {"id": f"cast:{who}:{attr}", "label": f"{who} — {attr}",
                     "type": kind}
                if attr == "gender":
                    f["options"] = sorted(bibles.VALID_GENDERS)
                return [f]
        return []
    if where == "recurring_cast" and ("too similar" in msg or "duplicate" in msg):
        names = [c["name"] for c in meta.get("recurring_cast") or []]
        hit = [n for n in names if n in msg or n.lower() in msg]
        return [{"id": f"cast:{n}:name", "label": f"{n} — name", "type": "text",
                 "value": n} for n in hit]
    return []


def check(pv: Preview, cfg: dict | None = None) -> list[dict]:
    """`bibles.validate` on the text promote would write, without writing it
    where the pipeline would see it."""
    with tempfile.TemporaryDirectory() as tmp:
        d = Path(tmp) / pv.name
        d.mkdir()
        path = d / f"{pv.name}.md"
        path.write_text(pv.text)
        real = pv.bible.parent
        for extra in [real / f"{pv.name}.cast"] + [real / v for v in
                                                  (pv.meta.get("assets") or {}).values()]:
            if extra.exists():
                (d / extra.name).symlink_to(extra.resolve())
        found = bibles.validate(path, cfg or {})
    out = []
    for p in found:
        fields = _fields_for(p, pv.meta)
        # validate's advice is written for a bible's YAML; a draft has none, and
        # the field saves the value as a labelled line instead.
        fix = DRAFT_FIX.get(p.where, p.fix) if fields else p.fix
        out.append({"fatal": p.fatal, "where": p.where, "message": p.message,
                    "fix": fix, "fields": fields})
    return out


DRAFT_FIX = {
    "genre": "Pick one; it is saved to the draft as a `Genre:` line under the title.",
    "series": "Saved to the draft as a `Series:` line under the title.",
    "anchor_year": "Saved to the draft as an `Anchor year:` line under the title.",
}


def preview(name: str, cfg: dict | None = None,
            bibles_dir: str | Path | None = None) -> Preview:
    cfg = cfg or {}
    pv = build(name, bibles_dir or cfg.get("bibles_dir", "bibles"))
    pv.problems = check(pv, cfg)
    return pv


